import dotenv from 'dotenv'
import oracledb from 'oracledb'

dotenv.config()

oracledb.outFormat = oracledb.OUT_FORMAT_OBJECT

const hasOracleConfig = () =>
  Boolean(process.env.ORACLE_USER && process.env.ORACLE_PASSWORD && process.env.ORACLE_CONNECTION_STRING)

const getConnection = async () => {
  if (!hasOracleConfig()) {
    throw new Error('Oracle no configurado')
  }

  return oracledb.getConnection({
    user: process.env.ORACLE_USER,
    password: process.env.ORACLE_PASSWORD,
    connectString: process.env.ORACLE_CONNECTION_STRING,
  })
}

const initSchema = async () => {
  if (!hasOracleConfig()) {
    return
  }

  const connection = await getConnection()

  try {
    await connection.execute(`
      CREATE TABLE PEOPLE_RANKING (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        NAME VARCHAR2(120) NOT NULL,
        AUTISM_POINTS NUMBER(10) DEFAULT 0 NOT NULL,
        ALCOHOL_POINTS NUMBER(10) DEFAULT 0 NOT NULL,
        YELLOW_CARDS NUMBER(10) DEFAULT 0 NOT NULL,
        CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
      )
    `)
    await connection.commit()
  } catch (error) {
    if (error.errorNum !== 955) {
      throw error
    }
  } finally {
    await connection.close()
  }
}

const listPeople = async () => {
  const connection = await getConnection()

  try {
    const result = await connection.execute(`
      SELECT
        ID AS "id",
        NAME AS "name",
        AUTISM_POINTS AS "autismPoints",
        ALCOHOL_POINTS AS "alcoholPoints",
        YELLOW_CARDS AS "yellowCards"
      FROM PEOPLE_RANKING
      ORDER BY CREATED_AT ASC
    `)

    return result.rows ?? []
  } finally {
    await connection.close()
  }
}

const insertPerson = async ({ name, autismPoints, alcoholPoints, yellowCards }) => {
  const connection = await getConnection()

  try {
    const result = await connection.execute(
      `
      INSERT INTO PEOPLE_RANKING (NAME, AUTISM_POINTS, ALCOHOL_POINTS, YELLOW_CARDS)
      VALUES (:name, :autismPoints, :alcoholPoints, :yellowCards)
      RETURNING ID INTO :id
      `,
      {
        name,
        autismPoints,
        alcoholPoints,
        yellowCards,
        id: { dir: oracledb.BIND_OUT, type: oracledb.NUMBER },
      },
    )

    await connection.commit()

    return {
      id: result.outBinds.id[0],
      name,
      autismPoints,
      alcoholPoints,
      yellowCards,
    }
  } finally {
    await connection.close()
  }
}

export { hasOracleConfig, initSchema, insertPerson, listPeople }
